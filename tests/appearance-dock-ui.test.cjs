// Real shell/frame navigation. The dock must stay outside page transforms and
// View Transition snapshots, with identical viewport geometry throughout.
const {test,before,after}=require('node:test'),assert=require('node:assert/strict');
const {Module}=require('node:module'),{readFileSync}=require('node:fs'),{resolve}=require('node:path');
const filename=resolve(__dirname,'files-host-ui.test.cjs'),m=new Module(filename);
m.filename=filename;m.paths=Module._nodeModulePaths(__dirname);
const original=m.require.bind(m);let start,stop;
m.require=id=>id==='node:test'?{test(){},before(fn){start=fn},after(fn){stop=fn}}:original(id);
m._compile(readFileSync(filename,'utf8')+'\nmodule.exports={open};',filename);
before(()=>start());after(()=>stop());


for(const width of [390,1440])test(`native theme cross-fades and rapid choices preserve the dock and editor at ${width}px`,async()=>{
 const t=await m.exports.open({width});try{
  await t.ctx.route('**/account/api/account/appearance',r=>r.fulfill({json:{signedIn:false}}));
  const script=readFileSync(resolve(__dirname,'../today/public/theme.js'),'utf8').split('// ==== InFlite Appearance: generated by .tools/appearance.mjs ====')[1].split('// ==== End InFlite Appearance ====')[0];
  await t.page.addScriptTag({content:script});
  await t.page.evaluate(()=>T.F.nav.go('/weather/',{kind:'section'}));
  const draft=t.page.getByRole('textbox',{name:'weather draft',exact:true});await draft.fill('Retain this view');
  await t.page.bringToFront();
  await t.page.emulateMedia({reducedMotion:'no-preference'});
  await t.page.evaluate(async()=>{await Promise.allSettled(document.getAnimations().filter(a=>a.effect?.getTiming().iterations!==Infinity).map(a=>a.finished));await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))});
  await t.page.evaluate(()=>{T.themeSamples=[];T.themeSampling=true;T.themeDraft=document.querySelector('[aria-label="weather draft"]');const sample=()=>{if(!T.themeSampling)return;const r=document.querySelector('.ws-dock').getBoundingClientRect();T.themeSamples.push({x:r.x,y:r.y,w:r.width,h:r.height});requestAnimationFrame(sample)};sample();});
  for(const pref of [{palette:'coast',appearance:'dark'},{palette:'iris',appearance:'light'},{palette:'ember',appearance:'dark'}]){
   await t.page.evaluate(pref=>InFliteAppearance.accept(pref,{animate:true}),pref);
   await t.page.waitForFunction(()=>!document.documentElement.classList.contains('ifl-colour-change'));
  }
  await t.page.evaluate(()=>{InFliteAppearance.accept({palette:'rose',appearance:'light'},{animate:true});InFliteAppearance.accept({palette:'graphite',appearance:'dark'},{animate:true});});
  await t.page.waitForFunction(()=>!document.documentElement.classList.contains('ifl-colour-change'));
  assert.equal(await t.page.evaluate(()=>InFliteAppearance.snapshot().palette),'graphite');
  assert.equal(await draft.inputValue(),'Retain this view');assert.equal(await draft.evaluate(el=>el===T.themeDraft),true);
  await t.page.evaluate(()=>new Promise(r=>{let n=0;const frame=()=>++n===5?r():requestAnimationFrame(frame);requestAnimationFrame(frame)}));
  const samples=await t.page.evaluate(()=>{T.themeSampling=false;return T.themeSamples;});assert.ok(samples.length>4);
  for(const r of samples)for(const k of ['x','y','w','h'])assert.ok(Math.abs(r[k]-samples[0][k])<=1,`dock ${k} changed during theme transition`);
  await t.clean();
 }finally{await t.ctx.close();}
});
